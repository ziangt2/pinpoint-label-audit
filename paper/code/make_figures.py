# ---------------------------------------------------------------- Figure 3: the two main findings
# (a) S1 reranking advantage, old vs current, three populations (robustness.json)
# (b) public evaluator's sensitivity metric, rank old -> current, fixed outputs (evaluator_sensitivity.json)
RB = json.loads((SD / "robustness.json").read_text())
EV = json.loads((SD / "evaluator_sensitivity.json").read_text())
fig = plt.figure(figsize=(FULL, 2.3))
a = fig.add_axes([0.125, 0.19, 0.30, 0.70])
b = fig.add_axes([0.655, 0.19, 0.14, 0.70])
pops = [("frame_2091", "Matched groups\n(2,091 queries)"), ("wider_non_frame", "Other unchanged\n(2,134 queries)"),
        ("wider_all", "All unchanged\n(4,225 queries)")]
for i, (k, lab) in enumerate(pops):
    for j, (v, c, mk) in enumerate((("adv_old", GRAY, "o"), ("adv_new", BLUE, "s"))):
        e, lo, hi = RB[k][v]
        yy = i + (-0.14 if j == 0 else 0.14)
        a.errorbar(e, yy, xerr=[[e - lo], [hi - e]], fmt=mk, color=c, ms=3.5, capsize=2, lw=0.9,
                   mfc=("white" if j == 0 else c), label=(("Old labels", "Current labels")[j] if i == 0 else None))
a.set(yticks=range(3), yticklabels=[p[1] for p in pops], ylim=(2.6, -0.6), xlim=(0, 0.085), xticks=[0, 0.02, 0.04, 0.06, 0.08])
a.set_xlabel("S1 reranking advantage in AP@10 (95% interval)", fontsize=6.8)
a.grid(axis="x", color="#EEEEEE", lw=0.5)
a.legend(loc="lower right", fontsize=6.3, handletextpad=0.3)
a.set_title("(a) Improvement size", loc="left", fontsize=7.5, weight="bold", pad=6)

runs = ["S1 reranked", "S1", "S2", "MetaCLIP2 Combined", "MetaCLIP2 SLERP", "MetaCLIP2 Text-only", "MetaCLIP2 Image-only"]
flip = [f for f in EV["sign_flips"] if f["metric"] == "P10" and f["both_intervals_exclude_zero"]]
hl = {x for f in flip for x in (f["a"], f["b"])}
o, n = EV["sensitivity_order"]["P10_old"], EV["sensitivity_order"]["P10_new"]
for r in runs:
    c = ORANGE if r in hl else ("#444444" if r == "MetaCLIP2 Image-only" else BLUE)
    ro, rn = o.index(r) + 1, n.index(r) + 1
    vo, vn = EV["runs"][r]["P10"]["old"][0], EV["runs"][r]["P10"]["new"][0]
    b.plot([0, 1], [ro, rn], color=c, lw=(1.5 if r in hl else 0.9), marker="o", ms=3.2, zorder=3 if r in hl else 2)
    nm = r.replace("MetaCLIP2 ", "MC2 ")
    b.text(-0.08, ro, f"{nm}  {vo:.3f}", ha="right", va="center", fontsize=6.2, color=c)
    b.text(1.08, rn, f"{vn:.3f}  {nm}", ha="left", va="center", fontsize=6.2, color=c)
b.set(xlim=(0, 1), ylim=(7.5, 0.5), xticks=[0, 1], yticks=[])
b.set_xticklabels(["Old labels", "Current labels"], fontsize=6.5)
for sp in ("left", "right", "top"):
    b.spines[sp].set_visible(False)
b.set_title("(b) Evaluator sensitivity rank (1 = largest P@10 range)", fontsize=7.5, weight="bold", pad=6)
save(fig, "fig3_main_findings")

